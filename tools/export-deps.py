#!/usr/bin/env python3
"""
Generate dist/normie-deps.list: the plain list of package names that the Update & Repair
button downloads from GitHub and installs on users' machines.

The XML files under components/normie/ are the single source of truth; this file is
generated from them so the two cannot drift apart.

  python3 tools/export-deps.py            write dist/normie-deps.list
  python3 tools/export-deps.py --check    exit 1 if the file is out of date (used by the tests)

Publishing flow: edit the XML -> run this -> commit both -> push. Machines pick up new
entries the next time their owner presses Update & Repair (once DEPS_LIST_URL is set).
Entries that do not exist on a given Fedora release are skipped by the client, not fatal.
"""
import glob
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "dist", "normie-deps.list")

HEADER = """# Normie Linux dependency list. GENERATED by tools/export-deps.py: do not edit by hand.
# One package name per line. The Update & Repair button installs any that are missing.
# Names only: it never runs anything from this file.
"""


# Image-only files: they describe what goes into the ISO (our own release/logo packages exist only in the
# local build repository), not what an installed system should be given.
IMAGE_ONLY = {"branding.xml"}


def build():
    names = set()
    for f in sorted(glob.glob(os.path.join(ROOT, "components", "normie", "*.xml"))):
        if os.path.basename(f) in IMAGE_ONLY:
            continue
        for p in ET.parse(f).getroot().iter("package"):
            n = p.get("name")
            if n and n.startswith("normie-"):
                continue                      # our own packages come from our repository, not from Fedora's
            if n and p.get("arch") in (None, "x86_64"):
                names.add(n)
    return HEADER + "\n".join(sorted(names, key=str.lower)) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if current == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"Wrote {OUT} ({text.count(chr(10)) - HEADER.count(chr(10))} packages)")
